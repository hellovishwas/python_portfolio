from tkinter import *
window=Tk()
window.geometry("325x400")
window.title("Calculator")
f=Frame(window,width=400,height=400,bg="grey")
f.propagate(0)
f.pack()
def btn(w,h,b,t,p,l,c=0):
    b=Button(f,width=w,height=h,bg=b,text=t,command=c)
    b.place(x=p,y=l)
def ent(n):
    entry.insert(END,n)
def clear_entry():
    entry.delete(0,"end")
def entry_perform():
    try:
        expression=entry.get()
        expression=expression.replace('✖',"*")
        expression=expression.replace('➗',"/")
        result=str(eval(expression))
        entry.delete(0,'end')
        entry.insert(0,result)
    except EXCEPTION :
        entry.delete(0,"end")
        entry.insert(0,"Error")
entry=Entry(window,width=100,bg="white")
entry.place(x=0,y=170)
btn(10,2,"white","➕",2,190,lambda:ent('+'))
btn(10,2,"white","➖",2,232,lambda:ent('-'))
btn(10,2,"white","✖",2,274,lambda:ent('x'))
btn(10,2,"white","➗",2,316,lambda:ent('÷'))
btn(10,2,"white","🟰",2,358, entry_perform)
