btn(10,2,"white",9,244,232,lambda:ent(9))
btn(10,2,"white",0,164,358,lambda:ent(0))
btn(10,2,"white",".",164,190,lambda:ent('.'))
btn(10,2,"white","π",83,190,lambda:ent("π"))
