text = "Hello, World!"

print(text.capitalize())      # Capitalizes first letter
print(text.casefold())        # Case-insensitive lower
print(text.center(20, '*'))   # Centers string with padding
print(text.count('o'))        # Counts occurrences of substring
print(text.encode())          # Encodes string to bytes
print(text.endswith('!'))     # Checks if ends with substring
print(text.expandtabs(4))     # Expands tabs to spaces
print(text.find('World'))     # Finds substring index
print(text.format())          # Formats string
print(text.index('o'))        # Index of substring
print(text.isalnum())         # Checks if alphanumeric
print(text.isalpha())         # Checks if alphabetic
print(text.isascii())         # Checks if ASCII
print(text.isdecimal())       # Checks if decimal
print(text.isdigit())         # Checks if digits
print(text.isidentifier())    # Checks if valid identifier
print(text.islower())         # Checks if all lowercase
print(text.isnumeric())       # Checks if numeric
print(text.isprintable())     # Checks if printable
print(text.isspace())         # Checks if whitespace
print(text.istitle())         # Checks if titlecased
print(text.isupper())         # Checks if all uppercase
print(','.join(['a', 'b']))   # Joins iterable with separator
print(text.ljust(20, '-'))    # Left justifies string
print(text.lower())           # Converts to lowercase
print(text.lstrip('H'))       # Strips chars from left
print(text.partition(','))    # Splits at first occurrence
print(text.replace('World', 'Python')) # Replaces substring
print(text.rfind('o'))        # Finds last occurrence
print(text.rindex('o'))       # Last index of substring
print(text.rjust(20, '-'))    # Right justifies string
print(text.rsplit(','))       # Splits from right
print(text.rstrip('!'))       # Strips chars from right
print(text.split(','))        # Splits string
print(text.splitlines())      # Splits at line breaks
print(text.startswith('Hello')) # Checks if starts with substring
print(text.strip('H!'))       # Strips chars from both ends
print(text.swapcase())        # Swaps case
print(text.title())           # Title cases string
print(text.upper())           # Converts to uppercase
print(text.zfill(20))         # Pads with zeros on left
